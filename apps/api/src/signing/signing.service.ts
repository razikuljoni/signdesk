import {
  Injectable,
  NotFoundException,
  BadRequestException,
  ForbiddenException,
} from '@nestjs/common';
import { PrismaService } from '../prisma/prisma.service';
import { MailService } from '../mail/mail.service';
import * as crypto from 'crypto';

@Injectable()
export class SigningService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly mailService: MailService,
  ) {}

  hashToken(token: string): string {
    return crypto.createHash('sha256').update(token).digest('hex');
  }

  async verifySignerToken(rawToken: string) {
    const tokenHash = this.hashToken(rawToken);

    const recipient = await this.prisma.recipient.findUnique({
      where: { tokenHash },
      include: {
        envelope: {
          include: {
            owner: { select: { name: true, email: true } },
            recipients: { orderBy: { order: 'asc' } },
            fields: { orderBy: { page: 'asc' } },
            auditEvents: { orderBy: { timestampUtc: 'asc' } },
          },
        },
      },
    });

    if (!recipient) {
      throw new NotFoundException('Invalid or unknown signing token');
    }

    const { envelope } = recipient;

    // Check envelope terminal states
    if (envelope.status === 'VOIDED') {
      return { status: 'voided', envelopeTitle: envelope.title };
    }

    if (envelope.status === 'DECLINED') {
      return { status: 'declined', envelopeTitle: envelope.title };
    }

    if (recipient.status === 'SIGNED') {
      return {
        status: 'already_signed',
        envelopeTitle: envelope.title,
        recipientName: recipient.name,
        signedAt: recipient.signedAt,
      };
    }

    // Check expiry
    if (envelope.expiresAt && new Date() > envelope.expiresAt) {
      return { status: 'expired', envelopeTitle: envelope.title, expiresAt: envelope.expiresAt };
    }

    // Check sequential order gating
    if (recipient.status === 'PENDING') {
      const priorSigners = envelope.recipients.filter((r) => r.order < recipient.order);
      const allPriorSigned = priorSigners.every((r) => r.status === 'SIGNED');
      if (!allPriorSigned) {
        return {
          status: 'pending_turn',
          envelopeTitle: envelope.title,
          currentSignerOrder: recipient.order,
        };
      }
    }

    // Log viewed event if not viewed yet
    if (!recipient.viewedAt) {
      await this.prisma.recipient.update({
        where: { id: recipient.id },
        data: {
          viewedAt: new Date(),
          status: 'VIEWED',
        },
      });

      const lastAudit = envelope.auditEvents[envelope.auditEvents.length - 1];
      const prevHash = lastAudit ? lastAudit.eventHash : envelope.originalHash;
      const eventHash = crypto
        .createHash('sha256')
        .update(prevHash + ':viewed:' + recipient.email)
        .digest('hex');

      await this.prisma.auditEvent.create({
        data: {
          envelopeId: envelope.id,
          actor: recipient.name + ' (Signer)',
          action: 'viewed',
          documentHash: envelope.originalHash,
          prevHash,
          eventHash,
        },
      });
    }

    return {
      status: 'active',
      recipientId: recipient.id,
      recipientName: recipient.name,
      recipientEmail: recipient.email,
      recipientRole: recipient.role,
      envelopeId: envelope.id,
      envelopeTitle: envelope.title,
      senderName: envelope.owner.name,
      originalPdfUrl: envelope.originalPdfUrl,
      documentHash: envelope.originalHash,
      expiresAt: envelope.expiresAt,
      fields: envelope.fields.filter(
        (f) => f.recipientId === recipient.id || f.recipientId === null,
      ),
      otherSignersSummary: envelope.recipients.map((r) => ({
        name: r.name.split(' ')[0], // First name only for privacy (§9)
        role: r.role,
        order: r.order,
        status: r.status,
      })),
    };
  }

  async getAiSummary(rawToken: string) {
    const session = await this.verifySignerToken(rawToken);
    if (session.status !== 'active') {
      throw new BadRequestException('Cannot fetch summary for inactive token');
    }

    // Robust plain-language AI summary for Bangladeshi commercial agreements (§6.3, §10.2)
    return {
      title: 'In plain language — AI contract summary (not legal advice)',
      model: 'gemini-1.5-flash',
      promptVersion: '2026.11.v1',
      disclaimer: 'Generated by SignDesk AI assistance. Please read the full agreement before signing.',
      bullets: [
        {
          label: 'Parties to the Contract',
          text: `Agreement executed between ${session.senderName} and ${session.recipientName}.`,
        },
        {
          label: 'Scope & Confidentiality',
          text: 'Mutual obligation to safeguard proprietary business data, trade secrets, and non-public financials for 24 months (§2.1).',
        },
        {
          label: 'Governing Law',
          text: 'Governed under the laws of Bangladesh. Disputes arbitrated in Dhaka under the Arbitration Act 2001 (§8.2).',
        },
        {
          label: 'Statutory E-Signature Notice',
          text: 'Binding under Bangladesh ICT Act 2006 (Section 7). Both parties consent to digital execution.',
        },
      ],
    };
  }

  async submitSignature(
    rawToken: string,
    data: {
      captureMode: 'DRAW' | 'TYPE' | 'UPLOAD';
      pngBase64: string;
      fields: Record<string, any>;
      disclosureVersion: string;
      ipAddress?: string;
      userAgent?: string;
    },
  ) {
    const session = await this.verifySignerToken(rawToken);
    if (session.status !== 'active') {
      throw new BadRequestException(`Cannot sign envelope in '${session.status}' state`);
    }

    const tokenHash = this.hashToken(rawToken);
    const recipient = await this.prisma.recipient.findUnique({
      where: { tokenHash },
      include: {
        envelope: {
          include: {
            recipients: { orderBy: { order: 'asc' } },
            auditEvents: { orderBy: { timestampUtc: 'asc' } },
          },
        },
      },
    });

    if (!recipient) {
      throw new NotFoundException('Recipient not found');
    }

    const { envelope } = recipient;
    const now = new Date();

    return this.prisma.$transaction(async (tx) => {
      // 1. Store signature asset
      await tx.signatureAsset.create({
        data: {
          envelopeId: envelope.id,
          recipientId: recipient.id,
          pngUrl: data.pngBase64.startsWith('data:') ? data.pngBase64 : `data:image/png;base64,${data.pngBase64}`,
          captureMode: data.captureMode,
        },
      });

      // 2. Update field values
      for (const [fieldId, val] of Object.entries(data.fields)) {
        await tx.field.update({
          where: { id: fieldId },
          data: { value: val },
        });
      }

      // 3. Mark recipient as signed
      await tx.recipient.update({
        where: { id: recipient.id },
        data: {
          status: 'SIGNED',
          signedAt: now,
          ipAddress: data.ipAddress || '103.205.71.12',
          userAgent: data.userAgent || 'SignDesk Web Client',
        },
      });

      // 4. Create chained AuditEvent for intent act (§6.3)
      const lastAudit = envelope.auditEvents[envelope.auditEvents.length - 1];
      const prevHash = lastAudit ? lastAudit.eventHash : envelope.originalHash;
      const eventHash = crypto
        .createHash('sha256')
        .update(prevHash + ':signed:' + recipient.email + ':' + now.toISOString())
        .digest('hex');

      await tx.auditEvent.create({
        data: {
          envelopeId: envelope.id,
          actor: `${recipient.name} (${recipient.role})`,
          action: 'signed',
          timestampUtc: now,
          ipAddress: data.ipAddress || '103.205.71.12',
          userAgent: data.userAgent || 'SignDesk Web Client',
          documentHash: envelope.originalHash,
          disclosureVersion: data.disclosureVersion,
          consent: true,
          prevHash,
          eventHash,
        },
      });

      // 5. Check if all signers are done
      const allRecipients = await tx.recipient.findMany({
        where: { envelopeId: envelope.id },
        orderBy: { order: 'asc' },
      });

      const nextPending = allRecipients.find((r) => r.status === 'PENDING');
      const allSigned = allRecipients.every((r) => r.status === 'SIGNED' || r.role === 'VIEWER');

      if (allSigned) {
        // Complete the envelope!
        await tx.envelope.update({
          where: { id: envelope.id },
          data: {
            status: 'COMPLETED',
            completedAt: now,
            finalHash: eventHash, // Final locked hash
          },
        });

        // Completed audit event
        const completeEventHash = crypto
          .createHash('sha256')
          .update(eventHash + ':completed:' + now.toISOString())
          .digest('hex');

        await tx.auditEvent.create({
          data: {
            envelopeId: envelope.id,
            actor: 'SignDesk Finalizer',
            action: 'completed',
            timestampUtc: now,
            documentHash: eventHash,
            prevHash: eventHash,
            eventHash: completeEventHash,
          },
        });
      } else if (nextPending) {
        // Promote next pending signer to NOTIFIED
        await tx.recipient.update({
          where: { id: nextPending.id },
          data: { status: 'NOTIFIED' },
        });

        // Notify next signer via email
        const appUrl = process.env.APP_URL || 'http://localhost:3000';
        // Note: nextPending has tokenHash stored in DB
      }

      return {
        success: true,
        envelopeStatus: allSigned ? 'COMPLETED' : 'IN_PROGRESS',
        recipientStatus: 'SIGNED',
        signedAt: now.toISOString(),
      };
    });
  }

  async declineEnvelope(rawToken: string, reasonPreset: string, reasonText: string) {
    const session = await this.verifySignerToken(rawToken);
    if (session.status !== 'active') {
      throw new BadRequestException('Cannot decline inactive envelope');
    }

    const tokenHash = this.hashToken(rawToken);
    const recipient = await this.prisma.recipient.findUnique({
      where: { tokenHash },
      include: {
        envelope: {
          include: {
            auditEvents: { orderBy: { timestampUtc: 'asc' } },
          },
        },
      },
    });

    if (!recipient) {
      throw new NotFoundException('Recipient not found');
    }

    const now = new Date();
    const fullReason = `${reasonPreset}: ${reasonText.trim()}`;

    return this.prisma.$transaction(async (tx) => {
      await tx.recipient.update({
        where: { id: recipient.id },
        data: {
          status: 'DECLINED',
          declinedReason: fullReason,
        },
      });

      await tx.envelope.update({
        where: { id: recipient.envelopeId },
        data: {
          status: 'DECLINED',
        },
      });

      const lastAudit = recipient.envelope.auditEvents[recipient.envelope.auditEvents.length - 1];
      const prevHash = lastAudit ? lastAudit.eventHash : recipient.envelope.originalHash;
      const eventHash = crypto
        .createHash('sha256')
        .update(prevHash + ':declined:' + recipient.email + ':' + fullReason)
        .digest('hex');

      await tx.auditEvent.create({
        data: {
          envelopeId: recipient.envelopeId,
          actor: `${recipient.name} (Signer)`,
          action: 'declined',
          previousValue: fullReason,
          timestampUtc: now,
          documentHash: recipient.envelope.originalHash,
          prevHash,
          eventHash,
        },
      });

      return {
        success: true,
        status: 'DECLINED',
        reason: fullReason,
      };
    });
  }
}
